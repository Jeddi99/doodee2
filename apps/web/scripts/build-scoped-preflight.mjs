/**
 * Generates `src/dd/preflight.generated.css` — Tailwind's Preflight reset, but
 * confined to the ported UI subtree instead of the whole document.
 *
 * Why this exists: the app runs two design systems side by side. The pages
 * ported from the Next.js `doodee` app are Tailwind-styled and need Preflight;
 * the pre-existing pages are styled by `src/styles.css`, which leans on browser
 * defaults Preflight removes (heading font-sizes, list markers, paragraph
 * margin-bottom, native button chrome). Preflight is global by construction, so
 * it cannot simply be turned on. Instead `corePlugins.preflight` is off in
 * `tailwind.config.js` and this script re-emits the same rules pre-scoped under
 * `.dd-ui`, which only the ported tree's root carries.
 *
 * The reset is generated rather than hand-copied because Preflight bakes
 * `theme()` lookups (font stacks, default border colour) into its output — a
 * hand-copy would silently drift from `tailwind.config.js`. Re-run after
 * changing `theme.fontFamily` or `theme.borderColor`:
 *
 *   npm run build:preflight --workspace @doodee/web
 *
 * Selector rewriting rules:
 *   `*`, `::before`, `::after`   → also match the root itself, then descendants
 *   `html`, `:host`, `body`      → collapse onto `.dd-ui` (it is the local root)
 *   anything else (`h1`, `button`, `[type='text']`, …) → `.dd-ui <selector>`
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import postcss from "postcss";
import tailwindcss from "tailwindcss";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, "..");
const SCOPE = ".dd-ui";

// Selectors that target the document root in Preflight. Inside the ported tree
// the local root IS `.dd-ui`, so these collapse onto the scope itself rather
// than becoming a (never-matching) `.dd-ui html`.
const ROOT_SELECTORS = new Set(["html", ":host", "body", ":root"]);

function scopeSelector(selector) {
  const trimmed = selector.trim();
  if (ROOT_SELECTORS.has(trimmed)) return SCOPE;
  // `*` must cover the root element too, not just its descendants — otherwise
  // `box-sizing: border-box` never lands on `.dd-ui` itself.
  if (trimmed === "*") return `${SCOPE}, ${SCOPE} *`;
  if (trimmed === "::before" || trimmed === "::after") return `${SCOPE} ${trimmed}`;
  return `${SCOPE} ${trimmed}`;
}

const source = "@tailwind base;";

// The real config is imported and spread rather than referenced by path:
// `tailwindcss({ config: <path>, ... })` reads the file and ignores the sibling
// keys, so a `corePlugins` override passed that way is silently dropped and the
// script emits only the `--tw-*` defaults. Spreading keeps theme and plugins in
// sync with the app while flipping preflight back on for this one run.
const { default: appConfig } = await import(
  pathToFileURL(resolve(appRoot, "tailwind.config.js")).href
);

const result = await postcss([
  tailwindcss({
    ...appConfig,
    // Nothing is scanned for utilities here — only the base layer is wanted —
    // but Tailwind errors on an empty `content`, so it is pointed at nothing.
    content: [{ raw: "", extension: "html" }],
    corePlugins: { ...appConfig.corePlugins, preflight: true },
  }),
]).process(source, { from: undefined });

const root = postcss.parse(result.css);

root.walkRules((rule) => {
  // `@keyframes` steps ("from", "0%") are not selectors and must not be scoped.
  if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  // Deduped because `html` and `:host` both collapse onto `.dd-ui`, which would
  // otherwise emit a pointless `.dd-ui, .dd-ui { … }`.
  rule.selectors = [
    ...new Set(rule.selectors.flatMap((s) => scopeSelector(s).split(",").map((x) => x.trim()))),
  ];
});

const banner = `/* GENERATED by scripts/build-scoped-preflight.mjs — do not edit by hand.
 * Tailwind Preflight, scoped to the ${SCOPE} subtree. See the script for why.
 * Regenerate: npm run build:preflight --workspace @doodee/web
 */\n`;

const out = resolve(appRoot, "src/dd/preflight.generated.css");
writeFileSync(out, banner + root.toString() + "\n");
console.log(`wrote ${out} (${root.nodes.length} top-level nodes)`);
